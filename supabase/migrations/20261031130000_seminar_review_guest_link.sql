-- Seminar review links accept submissions without login, like topic links.
-- A guest review keeps the self-entered name/student ID and an edit-code digest
-- (HMAC with the server secret; the code itself is never stored). Logging in
-- later lets the owner claim it with the same student ID and edit code.
-- Rollback: supabase/rollback/20261031130000_seminar_review_guest_link.rollback.sql (only while
-- no guest rows exist, or after deleting/claiming them).
begin;
set local lock_timeout = '5s';

alter table public.seminar_reviews
  alter column member_id drop not null,
  add column author_name text,
  add column student_id text,
  add column identity_kind text not null default 'member',
  add column edit_token_hash text;

alter table public.seminar_reviews
  add constraint seminar_reviews_identity_kind_check
    check (identity_kind in ('member', 'guest')),
  add constraint seminar_reviews_author_name_check
    check (author_name is null or char_length(btrim(author_name)) between 1 and 40),
  add constraint seminar_reviews_student_id_check
    check (student_id is null or student_id ~ '^[0-9]{4,12}$'),
  add constraint seminar_reviews_edit_token_hash_check
    check (edit_token_hash is null or edit_token_hash ~ '^[0-9a-f]{64}$'),
  add constraint seminar_reviews_identity_check check (
    (identity_kind = 'member' and member_id is not null and edit_token_hash is null)
    or (identity_kind = 'guest' and member_id is null and author_name is not null
        and student_id is not null and edit_token_hash is not null)
  );

-- One review per student ID per form (member rows store their student ID too).
create unique index seminar_reviews_form_student_uidx
  on public.seminar_reviews(form_id, student_id) where student_id is not null;

-- Revisions of guest reviews have no member.
alter table public.submission_revisions
  alter column member_id drop not null,
  drop constraint if exists submission_revisions_actor_kind_check,
  add constraint submission_revisions_actor_kind_check
    check (actor_kind in ('member', 'staff', 'guest'));

create table public.review_edit_attempts (
  id bigint generated by default as identity primary key,
  form_id uuid not null references public.seminar_review_forms(id) on delete cascade,
  request_hash text not null check (request_hash ~ '^[0-9a-f]{64}$'),
  action text not null check (action in ('submit', 'edit', 'claim')),
  succeeded boolean not null default false,
  created_at timestamptz not null default now()
);
create index review_edit_attempts_lookup_idx
  on public.review_edit_attempts(form_id, request_hash, action, created_at desc);

alter table public.review_edit_attempts enable row level security;
revoke all on table public.review_edit_attempts from public, anon, authenticated;
revoke all on sequence public.review_edit_attempts_id_seq from public, anon, authenticated;
grant select, insert, update, delete on table public.review_edit_attempts to service_role;
grant usage, select on sequence public.review_edit_attempts_id_seq to service_role;

commit;

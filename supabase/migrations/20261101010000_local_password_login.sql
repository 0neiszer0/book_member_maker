-- ID/password login that replaces Kakao: a per-semester shared signup code set by
-- officers, officer approval of new accounts, Argon2id password hashes, login
-- throttling, and officer-issued one-time setup/reset links (24h, digest only).
-- Kakao stays usable in parallel until cutover; members keep their rows.
-- Rollback: supabase/rollback/20261101010000_local_password_login.rollback.sql
begin;
set local lock_timeout = '5s';

alter table public.members
  add column auth_provider text,
  add column auth_session_version integer not null default 0;
alter table public.members
  add constraint members_auth_provider_check check (auth_provider is null or auth_provider in ('kakao', 'local'));
update public.members set auth_provider = 'kakao'
 where social_id is not null and social_id <> '' and social_id not like 'system:%';

create table public.member_credentials (
  member_id bigint primary key references public.members(id) on delete cascade,
  login_id text not null check (login_id ~ '^[a-z0-9_]{4,20}$'),
  password_hash text not null check (password_hash like '$argon2id$%'),
  status text not null default 'pending' check (status in ('pending', 'active')),
  signup_name text check (signup_name is null or char_length(signup_name) between 1 and 40),
  signup_student_id text check (signup_student_id is null or signup_student_id ~ '^[0-9]{4,20}$'),
  signup_department text check (signup_department is null or char_length(signup_department) <= 60),
  created_at timestamptz not null default now(),
  approved_at timestamptz,
  approved_by bigint references public.members(id) on delete set null,
  password_changed_at timestamptz not null default now()
);
create unique index member_credentials_login_id_uidx on public.member_credentials(login_id);

create table public.signup_codes (
  id bigint generated by default as identity primary key,
  term_id uuid references public.seminar_terms(id) on delete set null,
  code text not null check (char_length(code) between 6 and 40),
  created_by bigint references public.members(id) on delete set null,
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);
-- At most one code works at a time; setting a new one revokes the old one.
create unique index signup_codes_one_active_uidx on public.signup_codes((true)) where revoked_at is null;

create table public.account_setup_tokens (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete cascade,
  token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  created_by bigint references public.members(id) on delete set null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  used_at timestamptz
);
create index account_setup_tokens_member_idx on public.account_setup_tokens(member_id);

create table public.auth_failures (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('login', 'signup_code')),
  login_key text check (login_key is null or login_key ~ '^[0-9a-f]{64}$'),
  ip_key text not null check (ip_key ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now()
);
create index auth_failures_login_idx on public.auth_failures(kind, login_key, created_at desc);
create index auth_failures_ip_idx on public.auth_failures(kind, ip_key, created_at desc);

do $$
declare t text;
begin
  foreach t in array array['member_credentials', 'signup_codes', 'account_setup_tokens', 'auth_failures'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from public, anon, authenticated', t);
    execute format('grant select, insert, update, delete on table public.%I to service_role', t);
  end loop;
end $$;
revoke all on sequence public.signup_codes_id_seq, public.account_setup_tokens_id_seq, public.auth_failures_id_seq
  from public, anon, authenticated;
grant usage, select on sequence public.signup_codes_id_seq, public.account_setup_tokens_id_seq, public.auth_failures_id_seq
  to service_role;

commit;
